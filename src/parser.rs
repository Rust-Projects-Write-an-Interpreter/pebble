use std::fmt;

use crate::token::{Keyword, Token, TokenLiteral, TokenType};

#[derive(Debug, PartialEq)]
pub enum Literal {
    Boolean(bool),
    Nil,
    Number(f64),
    String(String),
}

impl fmt::Display for Literal {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        match self {
            Self::Boolean(b) => write!(f, "{b}"),
            Self::Nil => f.write_str("nil"),
            Self::Number(n) if n.fract() == 0.0 => write!(f, "{n:.1}"),
            Self::Number(n) => write!(f, "{n}"),
            Self::String(s) => f.write_str(s),
        }
    }
}

#[derive(Debug, PartialEq)]
pub enum Expression {
    Binary {
        left: Box<Self>,
        operator: Token,
        right: Box<Self>,
    },
    Group(Box<Self>),
    Literal(Literal),
    Unary {
        operator: Token,
        right: Box<Self>,
    },
}

impl fmt::Display for Expression {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        let name: String = match self {
            Self::Binary {
                left,
                operator,
                right,
            } => format!("({} {} {})", operator.lexeme, left, right),
            Self::Group(p) => format!("(group {})", p),
            Self::Literal(s) => s.to_string(),
            Self::Unary { operator, right } => format!("({} {})", operator.lexeme, right),
        };
        write!(f, "{}", name)
    }
}

pub struct Parser {
    // The list of tokens generated by
    // the scanner.
    pub tokens: Vec<Token>,

    // The index of the current token
    // in the tokens vector.
    pub index: usize,
}

impl Parser {
    // Return the current token as an Option.
    fn current_token(&self) -> Option<&Token> {
        self.tokens.get(self.index)
    }

    // Skip the current token, unless
    // we already reached the end.
    // Return the previous token.
    fn consume(&mut self) -> Option<&Token> {
        let previous = self.index;

        if self
            .current_token()
            .is_some_and(|t| t.ttype != TokenType::Eof)
        {
            self.index += 1;
        }

        self.tokens.get(previous)
    }

    // Check if the type of the current token
    // corresponds to the given `TokenType` variant.
    // `Option::filter` returns `Some` only when
    // the condition is satisfied.
    // So, in this case, only if the current token
    // is not `Eof` and if there is a match between
    // the current token and the given token type.
    fn check_current(&self, token_type: &TokenType) -> Option<&Token> {
        self.current_token()
            .filter(|t| t.ttype != TokenType::Eof && t.ttype == *token_type)
    }

    // Check if the type of the current token matches
    // one of the provided token types. If there is a
    // match, it consumes the token and returns it.
    fn match_current(&mut self, token_types: &[TokenType]) -> Option<&Token> {
        if token_types
            .iter()
            .any(|ttype| self.check_current(ttype).is_some())
        {
            self.consume()
        } else {
            None
        }
    }

    // Parse the next three tokens and try to
    // identify a binary operation that uses
    // one of the given operators.
    // Fall back to the provided next function
    // if the binary operation cannot be identified.
    //
    // binary -> next ( ( operators ) next )*
    fn binary(
        &mut self,
        operators: &[TokenType],
        next: fn(&mut Self) -> Option<Expression>,
    ) -> Option<Expression> {
        // Parse the left side of the binary operation.
        // This expression might be recursively
        // transformed if there is a chain of
        // binary operations.
        let mut expression = next(self)?;

        // Add the current operation to a
        // binary structure while the next token
        // matches one of the given operators.
        while let Some(t) = self.match_current(operators) {
            // Get the operator out of
            // self to allow further
            // mutable borrows.
            let operator = t.clone();

            // Parse the right side of
            // the binary operation.
            let right = next(self)?;

            // Transform the expression, adding
            // the previous one to the left side
            // recursively.
            expression = Expression::Binary {
                left: Box::new(expression),
                operator,
                right: Box::new(right),
            };
        }

        Some(expression)
    }

    // The main entry point of the parser.
    pub fn expression(&mut self) -> Option<Expression> {
        self.term()
    }

    // Parse the next three tokens and try to
    // identify an addition or a subtraction.
    //
    // term -> factor ( ( "+" | "-" ) factor )*
    fn term(&mut self) -> Option<Expression> {
        self.binary(&[TokenType::Plus, TokenType::Minus], Self::factor)
    }

    // Parse the next three tokens and try to
    // identify a multiplication or a division.
    //
    // factor -> unary ( ( "/" | "*" ) unary )*
    fn factor(&mut self) -> Option<Expression> {
        self.binary(&[TokenType::Slash, TokenType::Star], Self::unary)
    }

    // Parse the next two tokens and try to
    // identify a unary operation.
    //
    // unary -> ( "!" | "-" ) unary | primary
    fn unary(&mut self) -> Option<Expression> {
        if let Some(t) = self.match_current(&[TokenType::Bang, TokenType::Minus]) {
            return Some(Expression::Unary {
                operator: t.clone(),
                right: Box::new(self.unary()?),
            });
        }

        self.primary()
    }

    // Parse the current token and try to
    // identify a primary element.
    //
    // primary -> NUMBER | STRING | "true" | "false" | "nil" | "(" expression ")"
    fn primary(&mut self) -> Option<Expression> {
        // If the current token is None return None.
        let c: &Token = self.current_token()?;

        // Check the type of the current token.
        let result = match (&c.ttype, &c.literal) {
            (TokenType::Number, TokenLiteral::Number(n)) => {
                Expression::Literal(Literal::Number(*n))
            }
            (TokenType::Reserved(s), _) => match s {
                Keyword::True => Expression::Literal(Literal::Boolean(true)),
                Keyword::False => Expression::Literal(Literal::Boolean(false)),
                Keyword::Nil => Expression::Literal(Literal::Nil),
                _ => return None,
            },
            (TokenType::String, TokenLiteral::String(s)) => {
                Expression::Literal(Literal::String(s.to_string()))
            }
            (TokenType::LParen, _) => {
                // Consume the opening round bracket `(`.
                self.consume();

                // Parse the expression between brackets.
                let p = self.expression()?;

                // Check that the next token is
                // the closing round bracket `)`.
                // No need to consume it as it will
                // be consumed below as the valid token.
                self.check_current(&TokenType::RParen)?;

                Expression::Group(Box::new(p))
            }
            _ => {
                eprintln!("Invalid token  {}", c);
                return None;
            }
        };

        // If we reach this point, the token we
        // found was valid. Advance the index.
        self.index += 1;

        // Return the token as an Option.
        Some(result)
    }
}

