use std::fmt;

use crate::token::{Keyword, Token, TokenLiteral, TokenType};

#[derive(Debug, PartialEq)]
pub enum Literal {
    Boolean(bool),
    Nil,
    Number(f64),
    String(String),
}

impl fmt::Display for Literal {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        match self {
            Self::Boolean(b) => write!(f, "{b}"),
            Self::Nil => f.write_str("nil"),
            Self::Number(n) if n.fract() == 0.0 => write!(f, "{n:.1}"),
            Self::Number(n) => write!(f, "{n}"),
            Self::String(s) => f.write_str(s),
        }
    }
}

#[derive(Debug, PartialEq)]
pub enum Expression {
    Group(Box<Self>),
    Literal(Literal),
}

impl fmt::Display for Expression {
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        let name: String = match self {
            Self::Group(p) => format!("(group {})", p),
            Self::Literal(s) => s.to_string(),
        };
        write!(f, "{}", name)
    }
}

pub struct Parser {
    // The list of tokens generated by
    // the scanner.
    pub tokens: Vec<Token>,

    // The index of the current token
    // in the tokens vector.
    pub index: usize,
}

impl Parser {
    // Return the current token as an Option.
    fn current_token(&self) -> Option<&Token> {
        self.tokens.get(self.index)
    }

    // Skip the current token, unless
    // we already reached the end.
    fn consume(&mut self) {
        if self
            .current_token()
            .is_some_and(|t| t.ttype != TokenType::Eof)
        {
            self.index += 1;
        }
    }

    // Check if the type of the current token
    // corresponds to the given `TokenType` variant.
    // `Option::filter` returns `Some` only when
    // the condition is satisfied.
    // So, in this case, only if the current token
    // is not `Eof` and if there is a match between
    // the current token and the given token type.
    fn check_current(&self, token_type: &TokenType) -> Option<&Token> {
        self.current_token()
            .filter(|t| t.ttype != TokenType::Eof && t.ttype == *token_type)
    }

    // The main entry point of the parser.
    pub fn expression(&mut self) -> Option<Expression> {
        self.primary()
    }

    // Parse the current token and try to
    // identify a primary element.
    //
    // primary -> NUMBER | STRING | "true" | "false" | "nil" | "(" expression ")"
    fn primary(&mut self) -> Option<Expression> {
        // If the current token is None return None.
        let c: &Token = self.current_token()?;

        // Check the type of the current token.
        let result = match (&c.ttype, &c.literal) {
            (TokenType::Number, TokenLiteral::Number(n)) => {
                Expression::Literal(Literal::Number(*n))
            }
            (TokenType::Reserved(s), _) => match s {
                Keyword::True => Expression::Literal(Literal::Boolean(true)),
                Keyword::False => Expression::Literal(Literal::Boolean(false)),
                Keyword::Nil => Expression::Literal(Literal::Nil),
                _ => return None,
            },
            (TokenType::String, TokenLiteral::String(s)) => {
                Expression::Literal(Literal::String(s.to_string()))
            }
            (TokenType::LParen, _) => {
                // Consume the opening round bracket `(`.
                self.consume();

                // Parse the expression between brackets.
                let p = self.expression()?;

                // Check that the next token is
                // the closing round bracket `)`.
                // No need to consume it as it will
                // be consumed below as the valid token.
                self.check_current(&TokenType::RParen)?;

                Expression::Group(Box::new(p))
            }
            _ => {
                eprintln!("Invalid token  {}", c);
                return None;
            }
        };

        // If we reach this point, the token we
        // found was valid. Advance the index.
        self.index += 1;

        // Return the token as an Option.
        Some(result)
    }
}

#[cfg(test)]
mod tests {
    use crate::token::TokenLiteral;

    use super::*;

    fn dummy_token(ttype: TokenType) -> Token {
        Token {
            ttype,
            lexeme: String::new(),
            literal: TokenLiteral::Null,
        }
    }

    #[test]
    // Test that integer numbers are displayed
    // correctly with a decimal part of `.0`.
    fn test_literal_display_integer_number() {
        assert_eq!(Literal::Number(42.0).to_string(), "42.0");
    }

    #[test]
    // Test that float numbers are displayed
    // correctly with a decimal part.
    fn test_literal_display_decimal_number() {
        assert_eq!(Literal::Number(42.5).to_string(), "42.5");
    }

    #[test]
    // Test that the method `current_token`
    // returns the correct value.
    fn test_current_token() {
        let tokens = vec![dummy_token(TokenType::Identifier)];
        let parser = Parser { tokens, index: 0 };

        assert_eq!(
            parser.current_token(),
            Some(&dummy_token(TokenType::Identifier))
        );
    }

    #[test]
    // Test that consuming a token makes the
    // next one the current token.
    fn test_consume() {
        let tokens = vec![
            dummy_token(TokenType::Identifier),
            dummy_token(TokenType::Plus),
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        parser.consume();

        assert_eq!(parser.current_token(), Some(&dummy_token(TokenType::Plus)));
    }

    #[test]
    // Test that consuming `Eof` doesn't move
    // the index and keeps the current
    // token unchanged.
    fn test_consume_end() {
        let tokens = vec![dummy_token(TokenType::Eof)];
        let mut parser = Parser { tokens, index: 0 };
        parser.consume();
        parser.consume();

        assert_eq!(parser.current_token(), Some(&dummy_token(TokenType::Eof)));
    }

    #[test]
    // Test that consuming an empty list of
    // tokens just returns `None`.
    fn test_consume_empty() {
        let mut parser = Parser {
            tokens: vec![],
            index: 0,
        };
        parser.consume();

        assert_eq!(parser.current_token(), None);
    }

    #[test]
    fn test_check_current_true() {
        let tokens = vec![dummy_token(TokenType::Plus)];
        let parser = Parser { tokens, index: 0 };

        assert_eq!(
            parser.check_current(&TokenType::Plus),
            Some(dummy_token(TokenType::Plus)).as_ref()
        );
        assert_eq!(parser.index, 0);
    }

    #[test]
    fn test_check_current_false() {
        let tokens = vec![dummy_token(TokenType::Plus)];
        let parser = Parser { tokens, index: 0 };

        assert_eq!(parser.check_current(&TokenType::Number), None);
        assert_eq!(parser.index, 0);
    }

    #[test]
    fn test_check_current_end() {
        let tokens = vec![dummy_token(TokenType::Eof)];
        let parser = Parser { tokens, index: 0 };

        // If we reached the end of the token sequence
        // we return `None` without checking the type.
        assert_eq!(parser.check_current(&TokenType::Eof), None);
        assert_eq!(parser.index, 0);
    }

    #[test]
    // Test that the method `primary` works
    // correctly on a list of tokens that
    // contains reserved word `true`.
    fn test_primary_true() {
        let tokens = vec![
            dummy_token(TokenType::Reserved(Keyword::True)),
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        let result = parser.primary();

        assert_eq!(result, Some(Expression::Literal(Literal::Boolean(true))));
        assert_eq!(parser.index, 1);
    }

    #[test]
    // Test that the method `primary` works
    // correctly on a list of tokens that
    // contains reserved word `false`.
    fn test_primary_false() {
        let tokens = vec![
            dummy_token(TokenType::Reserved(Keyword::False)),
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        let result = parser.primary();

        assert_eq!(result, Some(Expression::Literal(Literal::Boolean(false))));
        assert_eq!(parser.index, 1);
    }

    #[test]
    // Test that the method `primary` works
    // correctly on a list of tokens that
    // contains reserved word `nil`.
    fn test_primary_nil() {
        let tokens = vec![
            dummy_token(TokenType::Reserved(Keyword::Nil)),
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        let result = parser.primary();

        assert_eq!(result, Some(Expression::Literal(Literal::Nil)));
        assert_eq!(parser.index, 1);
    }

    #[test]
    // Test that the method `primary` works
    // correctly on a list of tokens that
    // contains a reserved word that is
    // currently unknown.
    fn test_primary_unknown_reserved() {
        let tokens = vec![
            dummy_token(TokenType::Reserved(Keyword::Class)),
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        let result = parser.primary();

        assert_eq!(result, None);
        assert_eq!(parser.index, 0);
    }

    #[test]
    // Test that the method `primary` works
    // correctly on a list of tokens that
    // contains an integer number.
    fn test_primary_number_integer() {
        let tokens = vec![
            Token {
                ttype: TokenType::Number,
                lexeme: String::new(),
                literal: TokenLiteral::Number(123.0),
            },
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        let result = parser.primary();

        assert_eq!(result, Some(Expression::Literal(Literal::Number(123.0))));
        assert_eq!(parser.index, 1);
    }

    #[test]
    // Test that the method `primary` works
    // correctly on a list of tokens that
    // contains a float number.
    fn test_primary_number_float() {
        let tokens = vec![
            Token {
                ttype: TokenType::Number,
                lexeme: String::new(),
                literal: TokenLiteral::Number(123.4),
            },
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        let result = parser.primary();

        assert_eq!(result, Some(Expression::Literal(Literal::Number(123.4))));
        assert_eq!(parser.index, 1);
    }

    #[test]
    // Test that the method `primary` works
    // correctly on a list of tokens that
    // contains a string.
    fn test_primary_string() {
        let tokens = vec![
            Token {
                ttype: TokenType::String,
                lexeme: String::new(),
                literal: TokenLiteral::String(String::from("Some string")),
            },
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        let result = parser.primary();

        assert_eq!(
            result,
            Some(Expression::Literal(Literal::String(String::from(
                "Some string"
            ))))
        );
        assert_eq!(parser.index, 1);
    }

    #[test]
    fn test_primary_group() {
        let tokens = vec![
            dummy_token(TokenType::LParen),
            Token {
                ttype: TokenType::Number,
                lexeme: String::new(),
                literal: TokenLiteral::Number(123.4),
            },
            dummy_token(TokenType::RParen),
            dummy_token(TokenType::Eof),
        ];
        let mut parser = Parser { tokens, index: 0 };
        let result = parser.primary();

        assert_eq!(
            result,
            Some(Expression::Group(Box::new(Expression::Literal(
                Literal::Number(123.4)
            ))))
        );
        assert_eq!(parser.index, 3);
    }
}
